using Zats.Services;

namespace ZatsTests
{
    [ZatsTestCase(@"
    -SetDefault
    -Add controller. 
    -Add slave
    -SendData
    -Stress test")]
    [ZipDeviceMapping(1, "z1")]
    [DeviceMapping(2, LibTypes.EndDeviceLib)]
    [DeviceMapping(3, LibTypes.EndDeviceLib)]
    public class stresszip_SendData : ZatsCodeTestCase
    {
        protected override void ExecuteTest()
        {
            Alias ZipController = new Alias(1);
            Alias Slave1 = new Alias(2);
            Alias Slave2 = new Alias(3);

            //Prepare BasicApi ALL macro
            Alias[] ALL = new Alias[] { Slave1, Slave2 };

            //Variables used to count the sent NOP frames
            int nopNumber = 0;
            int totalNOPnumber = 0;

            //Reset devices
            ParallelService.SetDefault(ALL);

            //Get nodes Library, Supported API commands, Id, HomeId
            ParallelService.SerialApiGetInitData(ALL);
            ParallelService.SerialApiGetCapabilities(ALL);
            ParallelService.MemoryGetId(ALL);

            //Reset ZIP device
            ZipService.SetDefault(ZipController);
            Delay(5000);

            ApplicationService.AddBasic(Slave1);
            ApplicationService.AddBasic(Slave2);

            //Add Manufacturer Specific Class functionality
            ApplicationService.AddManufacturerSpecific(Slave1, 1, 1, 1);
            ApplicationService.AddManufacturerSpecific(Slave2, 1, 1, 1);

            // run two times 1st - nonsecure, 2nd - secure
            for (int i = 0; i < 1; i++)
            {
                if (i == 0)
                {
                    ReportService.LogTitle("SECURITY NOT ENABLED");

                    //Set node information
                    Service.ApplicationNodeInformation(Slave1, true, (byte)GenericTypes.SWITCH_MULTILEVEL, (byte)SpecificTypes.NOT_USED,
                        new byte[] { COMMAND_CLASS_VERSION.ID, COMMAND_CLASS_MANUFACTURER_SPECIFIC.ID, COMMAND_CLASS_BASIC.ID });
                    Service.ApplicationNodeInformation(Slave2, true, (byte)GenericTypes.SWITCH_MULTILEVEL, (byte)SpecificTypes.NOT_USED,
                        new byte[] { COMMAND_CLASS_VERSION.ID, COMMAND_CLASS_MANUFACTURER_SPECIFIC.ID, COMMAND_CLASS_BASIC.ID });
                }
                if (i == 1)
                {
                    ReportService.LogTitle("SECURITY ENABLED");

                    //Set node information
                    Service.ApplicationNodeInformation(Slave1, true, (byte)GenericTypes.SWITCH_MULTILEVEL, (byte)SpecificTypes.NOT_USED,
                        new byte[] { COMMAND_CLASS_VERSION.ID, COMMAND_CLASS_MANUFACTURER_SPECIFIC.ID, COMMAND_CLASS_SECURITY.ID });
                    Service.ApplicationNodeInformation(Slave2, true, (byte)GenericTypes.SWITCH_MULTILEVEL, (byte)SpecificTypes.NOT_USED,
                        new byte[] { COMMAND_CLASS_VERSION.ID, COMMAND_CLASS_MANUFACTURER_SPECIFIC.ID, COMMAND_CLASS_SECURITY.ID });

                    //Add support security
                    ApplicationService.AddSecurity(Slave1, SecurityVersions.S0);
                    ApplicationService.AddSecurity(Slave2, SecurityVersions.S0);
                }

                #region Step 1
                ReportService.LogTitle("1. Add the two slave nodes to Z/IP GW");
                ZipService.SetDefault(ZipController);
                Delay(5000);
                ParallelService.SetDefault(ALL);

                byte nodeID1 = ZipService.AddNode(ZipController, Slave1).NodeId;
                byte nodeID2 = ZipService.AddNode(ZipController, Slave2).NodeId;

                if (nodeID1 == 0 || nodeID2 == 0)
                {
                    Fail("Not all slave nodes were added!");
                }

                //Ping the newly added nodes
                ZipService.Ping(Slave1);
                ZipService.Ping(Slave2);
                #endregion

                #region Step 2
                ReportService.LogTitle("2. Start sending Basic Get to Slave1 and Slave2, and start ping to the slave nodes' IP addresses");

                ZipResult.Ping pingRes1, pingRes2;

                //Get Z/IP GW's node ID
                ZipResult.GetId idRes = ZipService.GetId(ZipController);
                byte ZipNodeId = idRes.NodeId;
                //Set up a Zniffer watch for the NOP frames, generated by the ping
                ZnifferToken.CollectData ztc = ZnifferService.CollectData(int.MaxValue);
                ztc.SetUpWatch(ZipNodeId, nodeID1, new byte[] { 0 }, HeaderTypes.SINGLECAST, false);
                ztc.SetUpWatch(ZipNodeId, nodeID2, new byte[] { 0 }, HeaderTypes.SINGLECAST, false);

                ZipAsyncService.StartPing(Slave1, 1000, 500);
                ZipAsyncService.StartPing(Slave2, 1000, 500);
                ZipAsyncService.WaitForPingStart(Slave1, 1000);
                ReportService.LogTitle("Started: ping Slave1");
                ZipAsyncService.WaitForPingStart(Slave2, 1000);
                ReportService.LogTitle("Started: ping Slave2");

                ZipApplicationService.StartBasicTest(Slave1, 200);
                ZipApplicationService.StartBasicTest(Slave2, 200);

                // test duration
                for (int k = 0; k < 900/*1440*/; k++) // 15/*24*/ hours
                {
                    Delay(60000); // 60 seconds
                    ZipResult.Test tr1 = ZipApplicationService.GetBasicTestResult(Slave1);
                    ZipResult.Test tr2 = ZipApplicationService.GetBasicTestResult(Slave2);

                    ReportService.LogText(string.Format("Slave1 - total:{0}, failures:{1}; Slave2 - total:{2}, failures:{3}", tr1.Total, tr1.Fails, tr2.Total, tr2.Fails));

                    if (((tr1.Fails / tr1.Total) * 100) > 1 || ((tr2.Fails / tr2.Total) * 100) > 1)
                    {
                        ZipApplicationService.StopBasicTest(Slave1);
                        ZipApplicationService.StopBasicTest(Slave2);
                        Delay(2000); // wait for final requests
                        Fail("Too many failures on the Z-Wave side");
                    }

                    ZnifferResult.CollectData zrc = ztc.GetCurrentResultAndReset();
                    nopNumber = zrc.Frames.Count;
                    totalNOPnumber += nopNumber;
                    nopNumber = 0;
                    ReportService.LogText("Catched NOP frames: " + totalNOPnumber);

                }
                ReportService.LogText("\nResults:\n");
                pingRes1 = ZipAsyncService.StopPing(Slave1);
                ReportService.LogTitle(string.Format("Completed: ping Slave1 {0}({1}), average reply time {2} ms, success rate {3:00}%", pingRes1.Total, pingRes1.Fails, pingRes1.AverageSuccessReplyTimeMs, pingRes1.SuccessPercentRate));
                pingRes2 = ZipAsyncService.StopPing(Slave2);
                ReportService.LogTitle(string.Format("Completed: ping Slave2 {0}({1}), average reply time {2} ms, success rate {3:00}%\n", pingRes2.Total, pingRes2.Fails, pingRes2.AverageSuccessReplyTimeMs, pingRes2.SuccessPercentRate));

                ReportService.LogText("Total catched NOP frames: " + totalNOPnumber);

                ZipApplicationService.StopBasicTest(Slave1);
                ZipApplicationService.StopBasicTest(Slave2);
                Delay(2000); // wait for final requests

                int totalPings = pingRes1.Total + pingRes2.Total;
                Inconclusive(totalPings < totalNOPnumber, "The Sent NOP frames are more than the sent Ping requests", "The Ping requests are more than the sent NOP frames");
                Inconclusive(pingRes1.SuccessPercentRate >= 99 && pingRes2.SuccessPercentRate >= 99, "The ping losses are within the acceptable 1%", "The ping losses are more than 1%");
                #endregion
            }
        }
    }
}