            var expectRes = expectToken.WaitCompletedSignal();

            AssertIsTrue(sendDataRes);
            AssertIsTrue(expectRes);
            AssertIsTrue(_datagram.SequenceEqual(expectRes.Command));
            AssertIsTrue(zt.WaitCompletedSignal());
