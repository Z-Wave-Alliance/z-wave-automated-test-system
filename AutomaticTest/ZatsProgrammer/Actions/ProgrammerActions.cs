                        ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                    }
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                }
            }
            catch
            {
                ControllerManager.ShowMessage(Resources.ErrorCantLockBitsSet, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }
        }

        internal List<byte> OnLockBitsReadZW050x()
        {
            List<byte> lockBits = new List<byte>();
            if (ControllerManager.DocumentModel.PortInfo != null)
            {

                int progInterface = ControllerManager.ProgInterface;
                if (progInterface == 0)
                {
                    ControllerManager.DoAction(() => LockBitsReadZW050x(lockBits), Resources.MsgLockBitsReadProgress);
                }
            }
            else
            {
                ControllerManager.ShowMessage(Resources.MsgInterfaceNotSelected, true);
            }
            return lockBits;
        }

        public void LockBitsReadZW050x(List<byte> lockBits)
        {
            var device = ControllerManager.DeviceOpen();
            try
            {
                ControllerManager.ShowMessageInConsole(Resources.MsgLockBitsReadProgress);
                if (device.SetProgrammingMode(true))
                {
                    device.ReadSignatureBits();
                    if (CheckDeviceChipTypeCompatibility(device))
                    {
                        device.SetBusyLedState(true);
                        for (int i = 0; i < 9; i++)
                        {
                            lockBits.Add(device.ReadLockBit(i));
                        }
                        device.SetBusyLedState(false);
                        if (!ControllerManager.DocumentModel.Settings.HoldDeviceInReset)
                            device.SetProgrammingMode(false);
                    }
                    else
                    {
                        ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                    }
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                }
            }
            catch
            {
                ControllerManager.ShowMessage(Resources.ErrorCantLockBitsRead, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }
        }
    }

    // Context for AES-128 CTR DRBG
    [StructLayout(LayoutKind.Sequential)]
    public struct CTR_DRBG_CTX
    {
        readonly byte _df;    /**< Use DF or not */
        [MarshalAs(UnmanagedType.ByValArray, SizeConst = 16)]
        readonly byte[] _v;   /**< Internal working state */
        [MarshalAs(UnmanagedType.ByValArray, SizeConst = 16)]
        readonly byte[] _k;   /**< Key working state */


        readonly uint _c;     /**< Reseed counter */

        public override string ToString()
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("df - " + Tools.GetHex(_df));
            sb.AppendLine("v - " + Tools.GetHex(_v));
            sb.AppendLine("k - " + Tools.GetHex(_k));
            sb.AppendLine("c - " + _c);
            return sb.ToString();
        }

        public CTR_DRBG_CTX(byte df, byte[] v, byte[] k, uint c)
        {
            _df = df;
            _v = v;
            _k = k;
            _c = c;
        }
    }
