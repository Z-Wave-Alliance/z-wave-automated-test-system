        public int UpgradeLatestFirmware()
        {
            int result = -1;
            int versionGood = 0;
            int revisionGood = 0;
            string versionID = "ZWAVE_PROGRAMMER_VERSION_VVI_4523@7740=";
            byte[] versionData = HexFileHelper.FromIntelHexData(Resources.ZWaveProgrammer_FW, Constants.BLANK_VALUE, 0, Constants.FIRMWARE_SIZE);
            if (versionData != null)
            {
                int i, j;
                for (i = 0; i < versionData.Length; i++)
                {
                    for (j = 0; j < versionID.Length; j++)
                    {
                        if ((char)versionData[i + j] != versionID[j])
                        {
                            break;
                        }
                    }
                    if (j == versionID.Length)
                    {
                        break;
                    }
                }
                if (i != versionData.Length)
                {
                    versionGood = (int)versionData[i + versionID.Length + 0];
                    revisionGood = (int)versionData[i + versionID.Length + 1];
                    if (ControllerManager.Actions.ProgrammerActions.GetCurrentFirmwareVersion(out int version, out int revision))
                    {
                        if (version != versionGood || revision != revisionGood)
                        {
                            try
                            {
                                ControllerManager.ShowConsoleConfirmMessage(Resources.MsgFirmwareUpdateConfirmation, true);

                                String fwGoodHexFileName = Path.GetTempFileName();
                                StreamWriter sw = File.AppendText(fwGoodHexFileName);
                                sw.Write(Resources.ZWaveProgrammer_FW);
                                sw.Close();
                                if (ControllerManager.Actions.ProgrammerActions.UpgradeFirmware(fwGoodHexFileName))
                                {
                                    if (ControllerManager.Actions.ProgrammerActions.GetCurrentFirmwareVersion(out version, out revision))
                                    {
                                        ControllerManager.ShowMessage(Resources.MsgFirmwareUpgradedSuccesful, false);
                                        result = 0;
                                    }
                                }
                                File.Delete(fwGoodHexFileName);
                            }
                            catch
                            {
                                ControllerManager.ShowMessage(Resources.ErrorCantUpgradeFirmware, true);
                            }
                        }
                        else
                        {
                            result = 1;
                        }
                    }

                }
            }
            return result;
        }

