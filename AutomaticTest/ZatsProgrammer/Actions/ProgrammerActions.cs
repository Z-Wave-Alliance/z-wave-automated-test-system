        public const int KeySize = 16;
        public const ushort PersonalizationSize = 32;
        private static bool Is64Bit
        {
            get { return IntPtr.Size == 8; }
        }

        // Calculate the public key corresponding to a random key. The random key is usually a random
        // number. Both keys are 32-byte integers.
        // \param[out] q The public key korresponding to n.
        // \param[in] n The private key.

        [DllImport("s2crypto32", EntryPoint = "crypto_scalarmult_curve25519_base", CallingConvention = CallingConvention.Cdecl)]
        private extern static void CryptoScalarmultCurve25519Base_32([Out, MarshalAs(UnmanagedType.LPArray, SizeConst = KeySize)] byte[] public_key,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = KeySize)] byte[] private_key
            );

        [DllImport("s2crypto64", EntryPoint = "crypto_scalarmult_curve25519_base", CallingConvention = CallingConvention.Cdecl)]
        private extern static void CryptoScalarmultCurve25519Base_64([Out, MarshalAs(UnmanagedType.LPArray, SizeConst = KeySize)] byte[] public_key,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = KeySize)] byte[] private_key
            );

        private static void CryptoScalarmultCurve25519Base(byte[] public_key, byte[] private_key)
        {
            if (IntPtr.Size == 8) // 64 bit process.
            {
                CryptoScalarmultCurve25519Base_64(public_key, private_key);
            }
            else
            {
                CryptoScalarmultCurve25519Base_32(public_key, private_key);
            }
        }

        // Instantiate a DRBG
        // \param[out] The DBRG to instantiate and seed
        // \param[in] The 32-byte input entropy to seed the generator. MUST be generated by a truly random source, e.g. white radio noise.
        // \param[in] 32-byte personalization string of 0x00 repeated 32 times

        [DllImport("s2crypto64", EntryPoint = "AES_CTR_DRBG_Instantiate", CallingConvention = CallingConvention.Cdecl)]
        private extern static void AES_CTR_DRBG_Instantiate_64(ref CTR_DRBG_CTX ctx,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = 32)] byte[] entropy_input,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = 32)] byte[] personalization);

        [DllImport("s2crypto32", EntryPoint = "AES_CTR_DRBG_Instantiate", CallingConvention = CallingConvention.Cdecl)]
        private extern static void AES_CTR_DRBG_Instantiate_32(ref CTR_DRBG_CTX ctx,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = 32)] byte[] entropy_input,
            [In, MarshalAs(UnmanagedType.LPArray, SizeConst = 32)] byte[] personalization);

        private static void AES_CTR_DRBG_Instantiate(ref CTR_DRBG_CTX ctx, byte[] entropy_input, byte[] personalization)
        {
            if (Is64Bit)
            {
                AES_CTR_DRBG_Instantiate_64(ref ctx, entropy_input, personalization);
            }
            else
            {
                AES_CTR_DRBG_Instantiate_32(ref ctx, entropy_input, personalization);
            }
        }

        /* Generate 64 bytes of RNG output.
         * \param[inout] The DBRG to generate from
         * \param[out] The 16-byte buffer to write random data to.
         */

        [DllImport("s2crypto64", EntryPoint = "AES_CTR_DRBG_Generate", CallingConvention = CallingConvention.Cdecl)]
        private extern static int AES_CTR_DRBG_Generate_64(ref CTR_DRBG_CTX ctx,
            [MarshalAs(UnmanagedType.LPArray)] byte[] rand);

        [DllImport("s2crypto32", EntryPoint = "AES_CTR_DRBG_Generate", CallingConvention = CallingConvention.Cdecl)]
        private extern static int AES_CTR_DRBG_Generate_32(ref CTR_DRBG_CTX ctx,
            [MarshalAs(UnmanagedType.LPArray)] byte[] rand);

        private static int AES_CTR_DRBG_Generate(ref CTR_DRBG_CTX ctx, byte[] rand)
        {
            return Is64Bit ? AES_CTR_DRBG_Generate_64(ref ctx, rand) : AES_CTR_DRBG_Generate_32(ref ctx, rand);
        }

        /// <summary>
        /// Generates new CTR_DRBG_CTX
        /// </summary>
        /// <returns>CTR_DRBG_CTX object</returns>
        public static CTR_DRBG_CTX AES_CTR_DRBG_Instantiate()
        {
            var rand = new RNGCryptoServiceProvider();
            var entropy_input = new byte[PersonalizationSize];
            rand.GetBytes(entropy_input);

            var ctx = new CTR_DRBG_CTX();
            var personalization = new byte[PersonalizationSize];
            AES_CTR_DRBG_Instantiate(ref ctx, entropy_input, personalization);

            return ctx;
        }

        /// <summary>
        /// Gets 16 bytes of pseudo random data using specified CTR_DRBG_CTX
        /// </summary>
        /// <returns>16 bytes of pseudo random data</returns>
        public static byte[] GetRandomData(ref CTR_DRBG_CTX ctx)
        {
            var ret = new byte[KeySize];
            AES_CTR_DRBG_Generate(ref ctx, ret);
            return ret;
        }

        /// <summary>
        /// Gets 16 bytes of pseudo random data
        /// </summary>
        /// <returns>16 bytes of pseudo random data</returns>
        public static byte[] GetRandomData()
        {
            var ctx = AES_CTR_DRBG_Instantiate();
            var ret = new byte[KeySize];
            AES_CTR_DRBG_Generate(ref ctx, ret);
            return ret;
        }

        public static void GenerateKeys(byte[] priv, byte[] pub)
        {
            var index = 0;
            var ctx = AES_CTR_DRBG_Instantiate();
            while (index < priv.Length)
            {
                var tmp = new byte[KeySize];
                AES_CTR_DRBG_Generate(ref ctx, tmp);

                var needed = priv.Length - index;
                var count = tmp.Length > needed ? needed : tmp.Length;
                Array.Copy(tmp, 0, priv, index, count);
                index += count;
            }
            CryptoScalarmultCurve25519Base(pub, priv);
        }

