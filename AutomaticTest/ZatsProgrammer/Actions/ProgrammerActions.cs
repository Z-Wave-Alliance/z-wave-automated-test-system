        /// <summary>
        /// Erase the Flash.
        /// </summary>
        public void FlashErase()
        {
            ControllerManager.ShowMessageInConsole(Resources.MsgEraseFlashProgress);
            var device = ControllerManager.DeviceOpen();
            try
            {
                if (device.SetProgrammingMode(true))
                {
                    device.ReadSignatureBits();
                    if (CheckDeviceChipTypeCompatibility(device))
                    {
                        device.SetBusyLedState(true);
                        if (device.ChipType == (byte)ChipTypes.ZW050x)
                        {
                            byte[] nvrData = device.ReadNvr(0);
                            device.Flash.Erase(ControllerManager.DocumentModel.IsAsic);
                            ControllerManager.Actions.ZW050xFormActions.NvrWrite(nvrData, device);
                        }
                        else
                        {
                            device.Flash.Erase(ControllerManager.DocumentModel.IsAsic);
                        }

                        device.SetBusyLedState(false);
                    }
                    else
                    {
                        ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                    }
                    if (!ControllerManager.DocumentModel.Settings.HoldDeviceInReset)
                        device.SetProgrammingMode(false);
                    ControllerManager.ShowMessageInStatus(Resources.MsgEraseROMDone, false);
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                }
            }
            catch
            {
                ControllerManager.ShowMessage(Resources.ErrorCantEraseFlash, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }
        }

        /// <summary>
        /// Read the flash.
        /// </summary>
        /// <param name="fileName">Name of the file.</param>
        /// <returns></returns>
        public string FlashRead(string fileName)
        {
            string strStatuses = "";
            bool result = false;
            ControllerManager.ShowMessageInConsole(Resources.MsgReadFlashProgress);
            string flashReadData = "";
            var device = ControllerManager.DeviceOpen();

            ControllerManager.ChangeProgressInfo(ProgressStatuses.Read, 0, 0);
            try
            {
                if (device.SetProgrammingMode(true))
                {
                    device.ReadSignatureBits();
                    if (CheckDeviceChipTypeCompatibility(device))
                    {
                        device.SetBusyLedState(true);
                        device.Flash.ProgressChanged += new ZWave.Events.ProgressChangedEventHandler(OnDeviceMemoryProgressChanged);
                        device.Flash.Read(ControllerManager.DocumentModel.IsAsic);
                        device.Flash.ProgressChanged -= new ZWave.Events.ProgressChangedEventHandler(OnDeviceMemoryProgressChanged);
                        byte[] flashData = device.Flash.GetBytes();
                        flashReadData = HexFileHelper.WriteIntelHexFile(flashData, 0, flashData.Length, 0x10, Constants.BLANK_VALUE, false);
                        device.SetBusyLedState(false);
                        result = true;
                    }
                    else
                    {
                        ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                    }
                    if (!ControllerManager.DocumentModel.Settings.HoldDeviceInReset)
                        device.SetProgrammingMode(false);
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                }
            }
            catch (RequestTimeoutException rtException)
            {
                ControllerManager.ShowMessage(Resources.ErrorCantReadFlash, true);
            }
            catch (ApplicationLayerException alException)
            {
                ControllerManager.ShowMessage(Resources.ErrorCantReadFlash + "\n" + alException.Message, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }
            if (result)
            {
                if (!string.IsNullOrEmpty(fileName))
                {
                    try
                    {
                        if (!string.IsNullOrEmpty(flashReadData))
                        {
                            TextWriter writer = new StreamWriter(fileName);
                            writer.Write(flashReadData);
                            writer.Close();
                        }
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine(ex.Message);
                        result = false;
                    }
                }

                ControllerManager.ShowMessage(Resources.MsgReadROMDone + strStatuses, false);
            }
            return flashReadData;
        }

