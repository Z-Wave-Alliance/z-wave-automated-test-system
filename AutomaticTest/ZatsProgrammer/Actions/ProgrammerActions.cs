        public static byte[] CalculateCrc(byte[] flashDataRaw, out bool isCrcOk)
        {
            isCrcOk = true;
            byte[] crcBuf = new byte[flashDataRaw.Length];
            for (int j = 0; j < crcBuf.Length; j++)
                crcBuf[j] = flashDataRaw[j];

            byte[] flashDataRawCrc = new byte[4];
            flashDataRawCrc[0] = 0xFF;
            flashDataRawCrc[1] = 0xFF;
            flashDataRawCrc[2] = 0xFF;
            flashDataRawCrc[3] = 0xFF;

            if (flashDataRaw[flashDataRaw.Length - 4] != Constants.BLANK_VALUE ||
                flashDataRaw[flashDataRaw.Length - 3] != Constants.BLANK_VALUE ||
                flashDataRaw[flashDataRaw.Length - 2] != Constants.BLANK_VALUE ||
                flashDataRaw[flashDataRaw.Length - 1] != Constants.BLANK_VALUE)
            {
                flashDataRawCrc[0] = flashDataRaw[flashDataRaw.Length - 4];
                flashDataRawCrc[1] = flashDataRaw[flashDataRaw.Length - 3];
                flashDataRawCrc[2] = flashDataRaw[flashDataRaw.Length - 2];
                flashDataRawCrc[3] = flashDataRaw[flashDataRaw.Length - 1];

                crcBuf[crcBuf.Length - 4] = 0xFF;
                crcBuf[crcBuf.Length - 3] = 0xFF;
                crcBuf[crcBuf.Length - 2] = 0xFF;
                crcBuf[crcBuf.Length - 1] = 0xFF;
                isCrcOk = false;
            }

            ReverseBitsInBuf(crcBuf, 0, crcBuf.Length);
            uint[] crc_tab = Chksum_crc32gentab();
            uint crc = 0xFFFFFFFF;
            for (int i = 0; i < crcBuf.Length - 4; i++)
            {
                crc = ((crc >> 8) & 0x00FFFFFF) ^ crc_tab[(crc ^ crcBuf[i]) & 0xFF];
            }

            flashDataRaw[flashDataRaw.Length - 4] = (byte)(0x000000FF & crc);
            flashDataRaw[flashDataRaw.Length - 3] = (byte)(0x000000FF & (crc >> 8));
            flashDataRaw[flashDataRaw.Length - 2] = (byte)(0x000000FF & (crc >> 16));
            flashDataRaw[flashDataRaw.Length - 1] = (byte)(0x000000FF & (crc >> 24));
            ReverseBitsInBuf(flashDataRaw, flashDataRaw.Length - 4, 4);
            if (isCrcOk == false)
            {
                if (flashDataRawCrc[0] == flashDataRaw[flashDataRaw.Length - 4] &&
                    flashDataRawCrc[1] == flashDataRaw[flashDataRaw.Length - 3] &&
                    flashDataRawCrc[2] == flashDataRaw[flashDataRaw.Length - 2] &&
                    flashDataRawCrc[3] == flashDataRaw[flashDataRaw.Length - 1])
                {
                    isCrcOk = true;
                }
            }

            return flashDataRaw;
        }

        private static void ReverseBitsInBuf(byte[] buf, int offset, int len)
        {
            int i;

            for (i = offset; i < (len + offset); i++)
            {
                buf[i] = (byte)(((buf[i] << 4) & 0xF0) | ((buf[i] >> 4) & 0x0F));
                buf[i] = (byte)(((buf[i] << 2) & 0xCC) | ((buf[i] >> 2) & 0x33));
                buf[i] = (byte)(((buf[i] << 1) & 0xAA) | ((buf[i] >> 1) & 0x55));
            }
        }


        private static uint[] Chksum_crc32gentab()
        {
            uint[] crc_tab = new uint[256];
            uint crc, poly;
            int i, j;

            poly = 0xEDB88320;
            for (i = 0; i < 256; i++)
            {
                crc = (uint)i;
                for (j = 8; j > 0; j--)
                {
                    if ((crc & (uint)1) > 0)
                    {
                        crc = (crc >> 1) ^ poly;
                    }
                    else
                    {
                        crc >>= 1;
                    }
                }
                crc_tab[i] = crc;
            }
            return crc_tab;
        }

        public static string NVMChipTypeToString(NVMTypes NVMChipType)
        {
            string str = "";
            if (NVMChipType != NVMTypes.NVMInvalid)
            {
                str += Resources.MsgNVMChipType;
                switch (NVMChipType & NVMTypes.NVMTypeMask)
                {
                    case NVMTypes.NVMSerialEEPROM:
                        str += "Serial EEPROM";
                        break;

                    case NVMTypes.NVMSerialFlash:
                        str += "Serial Flash";
                        break;

                    case NVMTypes.NVMInvalid:
                        str += "Invalid";
                        break;

                    default:
                        str += "Unknown";
                        break;
                }

                str += " ";
                string type = NVMChipType.ToString();
                if (type != null && type.StartsWith("NVM"))
                {
                    type = type.Substring(3);
                }
                str += type;
                str += ". ";
            }
            return str;
        }

        /// <summary>
