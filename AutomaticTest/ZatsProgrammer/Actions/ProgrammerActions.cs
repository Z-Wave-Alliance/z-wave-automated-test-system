                Array.Copy(tmp, 0, nvrData, NVRData.PUK_ADDRESS, 32);
                Array.Copy(tmp, 0, nvrData, NVRData.PRK_ADDRESS, 32);
            }
            _nvr = nvrData;
            _nvr.CalculateCrc16();
            nvrData[NVRData.CRC16_ADDRESS] = _nvr.CRC16[0];
            nvrData[NVRData.CRC16_ADDRESS + 1] = _nvr.CRC16[1];

            IFlashSettings flashSettings = null;

            if (verify)
            {
                flashDataRaw = CalculateCrc(flashDataRaw, out bool isCrcOk);
