                strStatuses = string.Format(" State: {0} {1:X2}", (Constants.StateBits)state, state);
                if (state == 0x02)
                {
                    ClearAutoProg1(device);

                    if (ControllerManager.DocumentModel.Settings.ResetChipAfterProgramming == true)
                    {
                        device.Reset();
                    }
                    ControllerManager.ShowMessage(Resources.MsgProgramROMDone, false);
                }
                else
                {
                    writtenOk = false;
                    ControllerManager.ShowMessage(Resources.ErrorProgramROMFailed + strStatuses, true);
                }
            }
        }

