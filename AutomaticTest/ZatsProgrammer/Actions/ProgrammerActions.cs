                _nvr.TXCAL1 == 0xFF ||
                _nvr.TXCAL2 == 0xFF ||
                !IsNvrCrc16Valid(nvrData, _nvr))
            {
                calibrate = true;
            }
            if (ControllerManager.DocumentModel.IsAddSecurity2Keys && ControllerManager.DocumentModel.HasValidS2Keypair2Keys)
            {
                nvrData[NVRData.REV_ADDRESS] = 0x02;
                Array.Copy(ControllerManager.DocumentModel.PublicS2Key, 0, nvrData, NVRData.PUK_ADDRESS, 32);
                Array.Copy(ControllerManager.DocumentModel.PrivateS2Key, 0, nvrData, NVRData.PRK_ADDRESS, 32);
