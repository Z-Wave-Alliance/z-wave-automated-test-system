        /// <summary>
        /// Compare the Flash.
        /// </summary>
        /// <param name="fileName">Name of the file.</param>
        public void FlashCompare(string fileName)
        {
            ControllerManager.ShowMessageInConsole(Resources.MsgCompareFlashProgress);
            bool result = false;
            var device = ControllerManager.DeviceOpen();
            try
            {
                if (device.SetProgrammingMode(true))
                {
                    device.ReadSignatureBits();
                    if (CheckDeviceChipTypeCompatibility(device))
                    {
                        IFlashPage lastPage = null;
                        device.SetBusyLedState(true);
                        byte crcState = 0;
                        bool isFlashCrcOk = false;
                        if (device.ChipType == (byte)ChipTypes.ZW050x)
                        {
                            isFlashCrcOk = IsFlashCrc32Valid(device, out crcState);
                            lastPage = device.Flash.ReadPage(ControllerManager.DocumentModel.IsAsic, Constants.PAGES_IN_FLASH - 1);
                        }

                        string hexFileName;
                        IFlashSettings flashSettings;

                        hexFileName = fileName;
                        //We need to read the flash setting from the Program Memory,
                        // because flash settings can be changed relative the settings in the hex file.
                        // If we not read them, we will always get the error about the Program memory of the
                        // chip is not the same as program memory in the hex.
                        // We read the flash settings from the Program memory of the chip, and not from the
                        // command line, because currently command line command write the settings to the chip
                        // before writting the hex file to the chip. Therefore Program Memory of the chip always
                        // have updated flash setting. TODO: may be this should be changed, because OTP can be
                        // written only once.
                        try
                        {   //flash setting are not exist in empty chip, this would give the exception.
                            flashSettings = device.FlashReadRfOptions();
                        }
                        catch
                        {
                            //If flash settings cant be read from the chip - just ignore it.
                            flashSettings = null;
                        }

                        if (!string.IsNullOrEmpty(hexFileName) && File.Exists(hexFileName))
                        {
                            byte[] flashDataRaw = HexFileHelper.GetBytes(HexFileHelper.ReadIntelHexFile(hexFileName, Constants.BLANK_VALUE), device.FlashSize, Constants.BLANK_VALUE);
                            if (flashDataRaw != null)
                            {
                                bool isReadCompare = true;
                                if (device.ChipType == (byte)ChipTypes.ZW050x)
                                {
                                    flashDataRaw = CalculateCrc(flashDataRaw, out bool isCrcOk);
                                    int len = flashDataRaw.Length;
                                    result = flashDataRaw[len - 4] == lastPage.Buffer[Constants.BYTES_IN_PAGE - 4] &&
                                        flashDataRaw[len - 3] == lastPage.Buffer[Constants.BYTES_IN_PAGE - 3] &&
                                        flashDataRaw[len - 2] == lastPage.Buffer[Constants.BYTES_IN_PAGE - 2] &&
                                        flashDataRaw[len - 1] == lastPage.Buffer[Constants.BYTES_IN_PAGE - 1];
                                }

                                if (!result && isReadCompare)
                                {
                                    try
                                    {

                                        device.Flash.Read(ControllerManager.DocumentModel.IsAsic);
                                        IDevice _device = ControllerManager.ZWaveManager.ApplicationLayer.CreateDevice();
                                        _device.ChipType = device.ChipType;
                                        // new SortedList<int, List<IFlashPage>>();
                                        result = _device.Flash.Compare(ControllerManager.DocumentModel.IsAsic, device.Flash, flashSettings, flashDataRaw, out SortedList<int, List<byte[]>> diffs);
                                        ShowCompareResults(diffs, (ChipTypes)device.ChipType);
                                    }
                                    catch (ApplicationLayerException alException)
                                    {
                                        ControllerManager.ShowMessage(Resources.ErrorCantReadFlash + "\n" + alException.Message, true);
                                    }
                                }
                            }
                        }
                        else if (string.IsNullOrEmpty(hexFileName))
                        {
                            ControllerManager.ShowMessage("Hex file is not selected.", true);
                        }
                        else
                        {
                            ControllerManager.ShowMessage(string.Format("{0} does not exists.", hexFileName), true);
                        }
                        device.SetBusyLedState(false);
                        if (result)
                        {
                            ControllerManager.ShowMessage(Resources.MsgCompareFlashSuccesful, false);
                        }
                        else
                        {
                            ControllerManager.ShowMessage(Resources.MsgCompareFlashFailed, true);
                        }
                    }
                    else
                    {
                        ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                    }
                    if (!ControllerManager.DocumentModel.Settings.HoldDeviceInReset)
                        device.SetProgrammingMode(false);
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                }
            }
            catch
            {
                ControllerManager.ShowMessage(Resources.ErrorCantCompareFlash, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }
        }

        private static bool IsFlashCrc32Valid(IDevice device, out byte state)
        {
            device.Flash.RunCRCCheck();
            Thread.Sleep(50);
            state = device.Flash.CheckState();
            for (int i = 0; i < 10; i++)
            {
                if ((state & 0x02) == 0)
                {
                    Thread.Sleep(100);
                    state = device.Flash.CheckState();
                }
            }
            //mask 0x06 = 2nd bit crc done, 3rd bit crc error
            return (state & 0x06) == 0x02;
        }

        public IFlashSettings FlashReadOptions(out ChipTypes outChipType)
        {
            IFlashSettings flashSettings = null;
            ChipTypes deviceChipType = ChipTypes.UNKNOWN;
            outChipType = ChipTypes.UNKNOWN;
            var device = ControllerManager.DeviceOpen();
            try
            {
                if (device.SetProgrammingMode(true))
                {
                    device.ReadSignatureBits();
                    if (CheckDeviceChipTypeCompatibility(device))
                    {

                        deviceChipType = (ChipTypes)device.ChipType;
                        outChipType = deviceChipType;
                        flashSettings = device.FlashReadRfOptions();
                    }
                    else
                    {
                        ControllerManager.ShowMessage(Resources.MsgIncorrectChipType, true);
                    }
                    if (!ControllerManager.DocumentModel.Settings.HoldDeviceInReset)
                        device.SetProgrammingMode(false);
                }
                else
                {
                    ControllerManager.ShowMessage(Resources.ErrorCantSetProgrammingMode, true);
                }
                if (flashSettings != null && deviceChipType != ChipTypes.UNKNOWN)
                {
                    ControllerManager.ShowMessageInStatus("Read Flash Options completed.", false);
                }
            }
            catch
            {
                ControllerManager.ShowMessage(Resources.ErrorCantReadFlashOptions, true);
            }
            finally
            {
                ControllerManager.DeviceClose();
            }

            return flashSettings;
        }

