                            device.SetBusyLedState(false);
                            device.Memory.SwitchEEPROM(false, (int)ControllerManager.DocumentModel.Settings.EepromSize);
                        }
                        else
                        {
                            ControllerManager.ShowMessage(Resources.ErrorCantInitEEPROM, true);
                        }
