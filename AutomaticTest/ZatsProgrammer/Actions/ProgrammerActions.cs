            bool writtenOk = device.Flash.Write(ControllerManager.DocumentModel.IsAsic, flashDataRaw, flashSettings, false);
            device.Flash.ProgressChanged -= new ZWave.Events.ProgressChangedEventHandler(OnDeviceMemoryProgressChanged);

            byte state = 0xFF;
            state = device.Flash.CheckState();
